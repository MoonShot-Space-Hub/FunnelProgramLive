#!/usr/bin/env python3
"""Assemble the After Effects build script from spec.json.

    python3 tools/assemble_jsx.py spec.json ae/CASHTAGS_VSL_Build.jsx

Writes: a header comment (what the script builds and how to run it), then
`var SPEC = <spec.json>;`, then tools/ae_interpreter.jsx. The output is pure
ASCII: the JSON is dumped with ensure_ascii=True, so every non-ASCII character
(U+2028 and U+2029 included) becomes a \\uXXXX escape that ExtendScript reads
back as the original character.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
INTERPRETER = os.path.join(HERE, "ae_interpreter.jsx")


def ascii_line(value, limit=120):
    """A single-line, ASCII-only, comment-safe rendering of a spec string."""
    text = str(value).replace("\r", " ").replace("\n", " ")
    text = text.encode("ascii", "backslashreplace").decode("ascii")
    text = text.replace("*/", "* /")
    return text[:limit]


def count_layers(spec):
    total = 0
    by_type = {}
    for comp in spec.get("comps", []):
        for layer in comp.get("layers", []):
            total += 1
            t = layer.get("type", "?")
            by_type[t] = by_type.get(t, 0) + 1
    return total, by_type


def header(spec, spec_path):
    name = ascii_line(spec.get("name") or "CASHTAGS_VSL")
    comps = spec.get("comps", [])
    main_id = spec.get("main")
    main = next((c for c in comps if c.get("id") == main_id), None)
    total, by_type = count_layers(spec)
    types = ", ".join("%s %d" % (t, n) for t, n in sorted(by_type.items()))
    if main is not None:
        main_desc = '"%s" %sx%s, %s fps, %s s' % (
            ascii_line(main.get("name", main_id)), main.get("width"), main.get("height"),
            spec.get("fps"), main.get("duration"))
    else:
        main_desc = "(main comp '%s' not found in spec)" % ascii_line(main_id)
    output = spec.get("render", {}).get("output", "")
    lines = [
        "/*",
        " * %s - After Effects build script" % name,
        " *",
        " * GENERATED by tools/assemble_jsx.py from %s. Do not edit by hand: change the" % ascii_line(os.path.basename(spec_path)),
        " * spec (tools/build_spec.py) and assemble again. Contract: SCHEMA.md.",
        " *",
        " * What it builds (in a NEW project):",
        " *   - folders: %s" % ascii_line(", ".join(spec.get("folders", [])), 200),
        " *   - %d imported assets (footage, images, audio) from the folders next to this script" % len(spec.get("assets", [])),
        " *   - %d compositions, main %s" % (len(comps), main_desc),
        " *   - %d layers (%s) with editable text, shape layers," % (total, ascii_line(types, 200)),
        " *     masks, Drop Shadow / Gaussian Blur effects, audio levels and eased keyframes",
        " *   - %d comp markers on the main comp, a Render Queue item (H.264 when available)" % len(spec.get("markers", [])),
        " *     writing %s.mp4 next to this script" % ascii_line(output),
        " *   - saves %s.aep and build_log.txt next to this script" % name,
        " *",
        " * How to run:",
        " *   1. Install the Inter fonts first: every .otf in the Fonts folder next to this script",
        " *      (Inter-Regular, Medium, SemiBold, Bold, ExtraBold, Black). Restart After Effects.",
        " *   2. Keep this script in its package folder, next to Footage/, Images/, Audio/ and Fonts/.",
        " *   3. Optional, for build_log.txt: Preferences > Scripting & Expressions >",
        " *      Allow Scripts to Write Files and Access Network.",
        " *   4. In After Effects: File > Scripts > Run Script File... and choose this file.",
        " *      It asks to save the current project first (Cancel stops the build safely).",
        " *   5. Read the summary alert (and build_log.txt) for warnings, then render from the Render Queue.",
        " */",
        "",
    ]
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: python3 tools/assemble_jsx.py spec.json ae/CASHTAGS_VSL_Build.jsx\n")
        return 2
    spec_path, out_path = argv[1], argv[2]
    with open(spec_path, "r", encoding="utf-8") as f:
        spec = json.load(f)
    if not isinstance(spec, dict) or not isinstance(spec.get("comps"), list):
        sys.stderr.write("error: %s is not a spec document (needs a 'comps' list)\n" % spec_path)
        return 1
    with open(INTERPRETER, "r", encoding="utf-8") as f:
        interpreter = f.read()
    try:
        interpreter.encode("ascii")
    except UnicodeEncodeError as e:
        sys.stderr.write("error: %s must be pure ASCII (%s)\n" % (INTERPRETER, e))
        return 1

    payload = json.dumps(spec, ensure_ascii=True, allow_nan=False, indent=1)
    # ensure_ascii already escapes U+2028 / U+2029; keep the guard explicit.
    payload = payload.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")

    text = header(spec, spec_path) + "var SPEC = " + payload + ";\n\n" + interpreter
    if not text.endswith("\n"):
        text += "\n"
    text.encode("ascii")  # raises if anything non-ASCII slipped through

    out_dir = os.path.dirname(os.path.abspath(out_path))
    os.makedirs(out_dir, exist_ok=True)
    with open(out_path, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    total, _ = count_layers(spec)
    print("wrote %s (%d bytes, %d comps, %d layers, %d assets)" % (
        out_path, len(text), len(spec.get("comps", [])), total, len(spec.get("assets", []))))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
