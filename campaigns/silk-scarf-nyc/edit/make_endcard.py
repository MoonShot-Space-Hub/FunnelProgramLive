#!/usr/bin/env python3
"""Render the transparent 1080x1920 end-card overlay for the final shot (S5B).

The overlay holds a soft bottom scrim, an optional brand logo, a hairline rule
and the tagline. Typography is rendered here rather than generated by
Higgsfield so it stays sharp and stable.

Usage (from campaigns/silk-scarf-nyc):
    python3 edit/make_endcard.py                         # no logo: logo area left clean
    python3 edit/make_endcard.py --logo brand/logo.png   # with the supplied logo
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = Path(__file__).resolve().parent
W, H = 1080, 1920

# Layout keeps everything above y=1500, clear of the Reels/TikTok caption and
# button zones (bottom ~420 px, right ~140 px).
LOGO_BOX = (540 - 230, 1140, 540 + 230, 1290)  # centred slot, max 460 x 150
RULE_Y = 1338
TAGLINE_TOP = 1372
LINE_GAP = 66
CREAM = (239, 229, 212)


def tracked_line(draw, font, text, y, tracking_em, fill):
    """Draw one centred line of letter-spaced capitals."""
    tracking = font.size * tracking_em
    widths = [draw.textlength(ch, font=font) for ch in text]
    total = sum(widths) + tracking * (len(text) - 1)
    x = (W - total) / 2
    for ch, w in zip(text, widths):
        draw.text((x, y), ch, font=font, fill=fill)
        x += w + tracking


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tagline", default="TIMELESS LUXURY|IN EVERY DETAIL",
                    help="use | for a line break")
    ap.add_argument("--logo", type=Path, help="transparent PNG logo (optional)")
    ap.add_argument("--font", type=Path, default=HERE / "fonts" / "CormorantGaramond-VF.ttf")
    ap.add_argument("--out", type=Path, default=HERE / "endcard.png")
    args = ap.parse_args()

    card = Image.new("RGBA", (W, H), (0, 0, 0, 0))

    # Bottom scrim: eased gradient from transparent at y=980 to 67% espresso.
    scrim = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    sd = ImageDraw.Draw(scrim)
    start = 980
    for y in range(start, H):
        t = (y - start) / (H - start)
        sd.line([(0, y), (W, y)], fill=(22, 15, 11, int(172 * t * t * (3 - 2 * t))))
    card.alpha_composite(scrim)

    if args.logo:
        logo = Image.open(args.logo).convert("RGBA")
        bw, bh = LOGO_BOX[2] - LOGO_BOX[0], LOGO_BOX[3] - LOGO_BOX[1]
        scale = min(bw / logo.width, bh / logo.height)
        logo = logo.resize((round(logo.width * scale), round(logo.height * scale)), Image.LANCZOS)
        card.alpha_composite(logo, (LOGO_BOX[0] + (bw - logo.width) // 2,
                                    LOGO_BOX[1] + (bh - logo.height) // 2))

    text = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    td = ImageDraw.Draw(text)
    td.line([(540 - 75, RULE_Y), (540 + 75, RULE_Y)], fill=CREAM + (210,), width=2)
    font = ImageFont.truetype(str(args.font), 46)
    try:
        font.set_variation_by_name("SemiBold")
    except (OSError, ValueError):
        pass  # static fallback font
    for i, line in enumerate(args.tagline.split("|")):
        tracked_line(td, font, line.strip(), TAGLINE_TOP + i * LINE_GAP, 0.32, CREAM + (255,))

    # Soft shadow under rule and type for legibility on bright fabric.
    shadow = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    shadow.putalpha(text.getchannel("A").point(lambda a: a * 0.55))
    shadow = shadow.filter(ImageFilter.GaussianBlur(6))
    card.alpha_composite(shadow)
    card.alpha_composite(text)

    card.save(args.out)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
