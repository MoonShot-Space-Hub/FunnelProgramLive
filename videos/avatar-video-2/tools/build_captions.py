"""Build caption groups for index.html from assets/transcript.json.

Run from the project root:  python3 tools/build_captions.py
Writes captions/groups.js (window.CAPTION_GROUPS), which index.html loads.

Grouping: a new group starts after sentence/clause punctuation, after a pause of
0.25 s or more, after 4 words, or past ~22 weighted characters; a few hand-tuned
breaks keep phrases together.
Words inside SUPPRESS ranges are not captioned (a scene shows them instead).
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORDS = json.loads((ROOT / "assets/transcript.json").read_text())

# word index -> emphasis tone ("amber" keyword, "red" negative keyword)
EMPHASIS = {
    2: "amber", 4: "amber",            # shortage, money
    11: "red", 13: "red",              # holds ... back
    23: "amber", 25: "amber",          # learned, believe
    29: "amber",                       # doesn't
    40: "amber", 41: "amber",          # growing up
    61: "amber",                       # often
    66: "amber", 68: "amber",          # shaping, decisions
    72: "amber",                       # realizing
    77: "amber", 83: "amber",          # circumstances, everything
    88: "amber", 90: "amber", 91: "amber",  # questioning, old beliefs
    94: "amber", 96: "amber",          # change, habits
    104: "amber", 105: "amber",        # begin today
    110: "amber", 111: "amber",        # money beliefs
    114: "red", 116: "red",            # holding ... back
    120: "amber", 121: "amber", 122: "amber",  # free one hour
    124: "amber", 126: "amber",        # click, link
}

# word index ranges shown by scenes instead of captions (inclusive):
# 42-56 "Money hard to earn ... can never be wealthy." is c4-old-beliefs' kinetic typography
SUPPRESS = [(42, 56)]

MAX_WORDS = 4
MAX_CHARS = 22.0

# hand-tuned phrasing: start a new group at these word indices / never break before these
FORCE_BREAK_BEFORE = {3, 10, 14, 17, 24, 31, 38, 61, 63, 67, 69, 72, 76, 79, 82, 88, 89, 95, 99, 102, 109, 112, 121, 124}
NO_BREAK_BEFORE = {1, 2, 7, 12, 13, 19, 23, 27, 33, 37, 41, 60, 62, 66, 68, 71, 73, 75, 77, 78, 83, 91, 98, 101, 105, 108, 111, 116, 120, 123, 127}
PAUSE = 0.25
DURATION = 43.32  # composition length: no group may outlive the video
HOLD_AFTER = 0.35  # how long a group lingers after its last word when a pause follows


def suppressed(i):
    return any(a <= i <= b for a, b in SUPPRESS)


def display(text):
    return text.upper()


def weight(i, text):
    n = len(re.sub(r"[^\w']", "", text)) + 1
    return n * (1.3 if i in EMPHASIS else 1.0)


groups, cur = [], []
for i, w in enumerate(WORDS):
    if suppressed(i):
        if cur:
            groups.append(cur)
            cur = []
        continue
    if cur:
        prev = WORDS[cur[-1]]
        chars = sum(weight(j, WORDS[j]["text"]) for j in cur) + weight(i, w["text"])
        if i in NO_BREAK_BEFORE and not re.search(r"[.?!]$", prev["text"]):
            cur.append(i)
            continue
        if (
            i in FORCE_BREAK_BEFORE
            or re.search(r"[.,?!]$", prev["text"])
            or w["start"] - prev["end"] >= PAUSE
            or len(cur) >= MAX_WORDS
            or chars > MAX_CHARS
        ):
            groups.append(cur)
            cur = []
    cur.append(i)
if cur:
    groups.append(cur)

out = []
for gi, g in enumerate(groups):
    start = WORDS[g[0]]["start"]
    last_end = WORDS[g[-1]]["end"]
    nxt = groups[gi + 1] if gi + 1 < len(groups) else None
    next_start = WORDS[nxt[0]]["start"] if nxt else None
    following = WORDS[g[-1] + 1]["start"] if g[-1] + 1 < len(WORDS) else None
    if next_start is not None and next_start - last_end < 0.6 and not suppressed(g[-1] + 1):
        end = next_start - 0.02
    else:
        end = last_end + HOLD_AFTER
        if following is not None:  # never linger past the next spoken word, captioned or not
            end = min(end, following - 0.02)
    out.append(
        {
            "start": round(max(0.0, start - 0.04), 3),
            "end": round(min(end, DURATION - 0.02), 3),
            "words": [
                {
                    "text": display(WORDS[j]["text"]),
                    "start": round(WORDS[j]["start"], 3),
                    "end": round(WORDS[j]["end"], 3),
                    "tone": EMPHASIS.get(j, "") + (" long" if j in EMPHASIS and len(re.sub(r"[^A-Za-z]", "", WORDS[j]["text"])) >= 11 else ""),
                }
                for j in g
            ],
        }
    )

dest = ROOT / "captions/groups.js"
dest.parent.mkdir(exist_ok=True)
dest.write_text(
    "// Generated by tools/build_captions.py from assets/transcript.json. Do not edit by hand.\n"
    "window.CAPTION_GROUPS = " + json.dumps(out, indent=1) + ";\n"
)
print(f"{len(out)} groups -> {dest.relative_to(ROOT)}")
for g in out:
    print(f"{g['start']:6.2f}-{g['end']:6.2f}  " + " ".join(
        (w['text'] + ('*' if w['tone'].startswith('amber') else '!' if w['tone'].startswith('red') else '')) for w in g["words"]))
