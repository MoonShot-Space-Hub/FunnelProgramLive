"""Build timed English caption groups from captions/script.json (translated speech).

Run from the project root:  python3 tools/build_captions_translated.py
Writes captions/groups.js (window.CAPTION_GROUPS) in the same shape index.html's caption engine
reads: [{start, end, words: [{text, start, end, tone}]}].

Script syntax per phrase: words separated by spaces; `word@12.34` pins that word to the moment
it is spoken; `*word*` marks an amber keyword, `!word` a red one. Unpinned words are spread
between their neighbours (or the phrase window edges) in proportion to their length.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = json.loads((ROOT / "captions/script.json").read_text())

MAX_WORDS = 4
MAX_CHARS = 18.0
HOLD_AFTER = 0.35


def parse(token):
    m = re.match(r"^(.*?)(?:@(\d+(?:\.\d+)?))?([.,?!:;—]*)$", token)
    raw, at, trail = m.group(1), m.group(2), m.group(3)
    if at is None:  # no anchor: the punctuation was already part of the word
        raw, trail = raw + trail, ""
    tone = ""
    if raw.startswith("!"):
        tone, raw = "red", raw[1:]
    stars = re.match(r"^\*(.+?)\*(.*)$", raw)
    if stars:
        tone, raw = "amber", stars.group(1) + stars.group(2)
    return {"text": (raw + trail).upper(), "tone": tone, "at": float(at) if at else None}


def weight(text):
    return len(re.sub(r"[^\w']", "", text)) + 1.5


words = []
for phrase in SCRIPT["phrases"]:
    w0, w1 = phrase["window"]
    toks = [parse(t) for t in phrase["text"].split()]
    # pin anchors, then fill the gaps between known times by length
    known = [(-1, w0)] + [(i, t["at"]) for i, t in enumerate(toks) if t["at"] is not None] + [(len(toks), w1)]
    for (ia, ta), (ib, tb) in zip(known, known[1:]):
        gap = toks[ia + 1 : ib]
        if not gap:
            continue
        # the anchored word at ia keeps some of the span for itself
        lead = weight(toks[ia]["text"]) if ia >= 0 else 0.0
        total = lead + sum(weight(t["text"]) for t in gap)
        span = max(0.05, tb - ta)
        acc = lead
        for t in gap:
            t["at"] = round(ta + span * acc / total, 3)
            acc += weight(t["text"])
    for i, t in enumerate(toks):
        nxt = toks[i + 1]["at"] if i + 1 < len(toks) else w1
        t["end"] = round(max(t["at"] + 0.08, min(nxt, t["at"] + 0.9)), 3)
        t["phrase_end"] = w1
        t["last_in_phrase"] = i == len(toks) - 1
        words.append(t)

groups, cur = [], []
for w in words:
    if cur:
        prev = cur[-1]
        chars = sum(weight(x["text"]) * (1.3 if x["tone"] else 1) for x in cur) + weight(w["text"])
        if (prev["last_in_phrase"] or re.search(r"[.,?!:—]$", prev["text"])
                or len(cur) >= MAX_WORDS or chars > MAX_CHARS):
            groups.append(cur)
            cur = []
    cur.append(w)
if cur:
    groups.append(cur)

def span(g, nxt):
    end = nxt[0]["at"] if nxt else g[-1]["end"]
    return end - g[0]["at"]


# merge groups too brief to read into their neighbour (up to 5 words)
MIN_SPAN = 0.45
merged = True
while merged:
    merged = False
    for gi in range(len(groups) - 1):
        g, n = groups[gi], groups[gi + 1]
        if span(g, n) < MIN_SPAN and len(g) + len(n) <= 5:
            groups[gi : gi + 2] = [g + n]
            merged = True
            break

DURATION = SCRIPT.get("duration", 52.366)
out = []
for gi, g in enumerate(groups):
    nxt = groups[gi + 1][0]["at"] if gi + 1 < len(groups) else None
    end = g[-1]["phrase_end"] + HOLD_AFTER if g[-1]["last_in_phrase"] else g[-1]["end"]
    if nxt is not None:
        end = min(max(end, g[-1]["end"]), nxt - 0.02)
    end = min(end, DURATION - 0.02)
    out.append({
        "start": round(max(0.0, g[0]["at"] - 0.04), 3),
        "end": round(end, 3),
        "words": [{"text": w["text"], "start": w["at"], "end": w["end"], "tone": w["tone"]} for w in g],
    })

dest = ROOT / "captions/groups.js"
dest.write_text(
    "// Generated by tools/build_captions_translated.py from captions/script.json. Do not edit by hand.\n"
    "window.CAPTION_GROUPS = " + json.dumps(out, indent=1) + ";\n"
)
print(f"{len(out)} groups -> {dest.relative_to(ROOT)}")
for g in out:
    print(f"{g['start']:6.2f}-{g['end']:6.2f}  " + " ".join(
        w["text"] + ("*" if w["tone"] == "amber" else "!" if w["tone"] == "red" else "") for w in g["words"]))
